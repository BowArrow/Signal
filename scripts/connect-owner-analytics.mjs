import { spawn } from 'node:child_process';
import { mkdtempSync, unlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { build } = createRequire(require.resolve('vite'))('esbuild');
if (!process.argv.includes('--connect') && !process.argv.includes('--inspect') && !process.argv.includes('--diagnose')) throw new Error('Pass --inspect, --diagnose or --connect.');
const output = resolve('out/main/connect-owner-analytics.cjs');
await build({ entryPoints: ['scripts/connect-owner-analytics.ts'], outfile: output, bundle: true, platform: 'node', format: 'cjs', packages: 'external', define: { 'import.meta.url': JSON.stringify(pathToFileURL(output).href) }, logLevel: 'silent' });
const env = { ...process.env, SIGNAL_OFFLINE: '0', SIGNAL_ANALYTICS_HELPER_PROFILE: mkdtempSync(join(tmpdir(), 'signal-analytics-')) };
if (process.argv.includes('--reauthorize-cinegen')) env.SIGNAL_ANALYTICS_REAUTHORIZE_CINEGEN = '1';
if (process.argv.includes('--inspect')) env.SIGNAL_ANALYTICS_INSPECT = '1';
if (process.argv.includes('--diagnose')) env.SIGNAL_ANALYTICS_DIAGNOSE = '1';
delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(require('electron'), [output, '--disable-gpu'], { env, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
child.stdout.pipe(process.stdout); child.stderr.pipe(process.stderr);
child.on('exit', code => { unlinkSync(output); process.exitCode = code ?? 1; });
